#!/bin/bash
# The root half of 1792636073-camlink-4k.sh: what noble lacks for upstream's
# Cam Link 4K migration.
source "${REPO_DIR:?}/lib/common.sh"
need_root

# Omarchy's v4l2-relayd units before the package, whose postinst enables and
# starts the base service: here it does nothing, as on Arch, instead of
# relaying a test pattern into a "Virtual Camera".
install_file 644 /etc/systemd/system/v4l2-relayd.service <"$REPO_DIR/etc/systemd/system/v4l2-relayd.service"
install_file 644 /etc/systemd/system/v4l2-relayd@.service <"$REPO_DIR/etc/systemd/system/v4l2-relayd@.service"
install_file 644 /etc/modprobe.d/zz-omarchy-camlink-4k.conf <"$REPO_DIR/etc/modprobe.d/zz-omarchy-camlink-4k.conf"
# Upstream's camlink-4k-loopback.service runs /usr/bin/modprobe, where Arch
# keeps it; noble's is /usr/sbin/modprobe. Its commands as the tag has them,
# that path aside, so the drop-in follows the unit when upstream changes it.
loopback_unit=$OMARCHY_PATH/default/systemd/system/camlink-4k-loopback.service
[[ -f $loopback_unit ]] || die "the checkout has no $loopback_unit"
{
  echo "# Generated by the port from upstream's unit: modprobe at noble's path."
  echo "[Service]"
  echo "ExecStart="
  grep '^ExecStart=' "$loopback_unit" | sed 's#^ExecStart=/usr/bin/modprobe #ExecStart=/usr/sbin/modprobe #'
} | install_file 644 /etc/systemd/system/camlink-4k-loopback.service.d/10-omarchy-ubuntu.conf
systemctl daemon-reload

# DKMS builds the module against the running kernel's headers, which an
# Ubuntu kernel has as a package (upstream's omarchy-pkg-add then finds all
# three installed). setfacl, which upstream's migration runs on the device,
# is Arch's base and optional on noble.
headers=linux-headers-$(uname -r)
apt-cache show "$headers" >/dev/null 2>&1 || headers=""
apt_retry install -y --no-install-recommends ${headers:+"$headers"} v4l2loopback-dkms v4l2loopback-utils v4l2-relayd acl
# An earlier install's relay of the test pattern holds the module.
systemctl try-restart v4l2-relayd.service

# The devices come with the module's load: now when nothing holds it.
camlink_device() { grep -qsx "Cam Link 4K" /sys/devices/virtual/video4linux/*/name; }
if ! camlink_device; then
  if [[ -d /sys/module/v4l2loopback ]]; then
    if [[ $(cat /sys/module/v4l2loopback/refcnt 2>/dev/null) != 0 ]] || ! modprobe -r v4l2loopback; then
      warn "v4l2loopback is in use: the Cam Link 4K device comes with the next boot, and the next update finishes this"
      exit 75
    fi
  fi
  modprobe v4l2loopback
  camlink_device || die "v4l2loopback loaded without a Cam Link 4K device; see /etc/modprobe.d/zz-omarchy-camlink-4k.conf"
fi
note "Cam Link 4K loopback device in place"
